/**
 * CODEGEN for the cel icon compiler (estudos-sota M8 — SÍNTESE §2.12; r9
 * §7.4): compiled layers → components/icons/generated.ts (typed path data
 * per icon and layer, consumed by <Icon>) and public/icons/sprite.svg
 * (`<symbol id>` per icon, for plugins, `<use href>` and the canvas atlas).
 *
 * Both outputs paint each layer with the SAME expression
 * (components/icons/tones.ts layerPaint): an `--icon-*` override, else
 * the icon's default tone token from the cel block of app/globals.css.
 * Outside a cel theme those tokens are undefined, so the tone layers fall
 * back to transparent and the ink to currentColor: classic themes get
 * clean line icons, cel themes the toned version.
 *
 * Pure: strings in, strings out (the CLI in compile.ts does the I/O).
 */

import type { CompiledIcon } from "./compile.ts";
import { layerPaint } from "../../components/icons/tones.ts";

const HEADER = (what: string) =>
	`GENERATED by scripts/icons/compile.ts from scripts/icons/defs/*.ts — do not edit; run \`npx tsx scripts/icons/compile.ts\`. ${what}`;

const q = (s: string) => JSON.stringify(s);

/** components/icons/generated.ts */
export function emitGenerated(icons: readonly CompiledIcon[], aliases: Readonly<Record<string, string>> = {}): string {
	const names = new Set(icons.map((i) => i.name));
	for (const [alias, target] of Object.entries(aliases)) {
		if (names.has(alias)) throw new Error(`alias "${alias}" collides with an icon of the same name`);
		if (!names.has(target)) throw new Error(`alias "${alias}" points at unknown icon "${target}"`);
	}
	const L: string[] = [
		"/**",
		` * ${HEADER("Cel icon layers (SÍNTESE §2.12; r9 §7–§8):")}`,
		" * fill/shade = flat tones, ink = hand-inked outline (currentColor),",
		" * …OnFill = the ink drawn entirely over the tone (--cel-on-fill),",
		" * hl = specular, micro = ≤16 px ink, boil = live-state ink frames 2–3.",
		" */",
		"",
		'import type { IconTone } from "./tones.ts";',
		"",
		"/** Path data of one icon, per cel layer, in `0 0 grid grid` units. */",
		"export interface IconLayers {",
		"\treadonly label: string;",
		'\treadonly family: "glyph" | "object" | "display";',
		"\treadonly grid: 24 | 48;",
		"\t/** Default tone of the fill/shade layers. */",
		"\treadonly tone?: IconTone;",
		"\t/** Ink on the ground: the outline and strokes not entirely over the tone. */",
		"\treadonly ink: string;",
		"\t/** Ink entirely over the tone (letters, checks, hands), painted --cel-on-fill. */",
		"\treadonly inkOnFill?: string;",
		"\treadonly fill?: string;",
		"\treadonly shade?: string;",
		"\treadonly hl?: string;",
		"\treadonly micro?: string;",
		"\treadonly microOnFill?: string;",
		"\treadonly boil?: readonly [string, string];",
		"\treadonly boilOnFill?: readonly [string, string];",
		"}",
		"",
		"/** Every icon name (kebab-case, semantic — r9 §8.4). */",
		"export type IconName =",
	];
	icons.forEach((icon, i) => L.push(`\t| ${q(icon.name)}${i === icons.length - 1 ? ";" : ""}`));
	L.push("", "export const ICONS: Readonly<Record<IconName, IconLayers>> = {");
	for (const icon of icons) {
		L.push(`\t${q(icon.name)}: {`, `\t\tlabel: ${q(icon.label)},`, `\t\tfamily: ${q(icon.family)},`, `\t\tgrid: ${icon.grid},`);
		if (icon.tone) L.push(`\t\ttone: ${q(icon.tone)},`);
		L.push(`\t\tink: ${q(icon.ink)},`);
		if (icon.inkOnFill !== undefined) L.push(`\t\tinkOnFill: ${q(icon.inkOnFill)},`);
		if (icon.fill !== undefined) L.push(`\t\tfill: ${q(icon.fill)},`);
		if (icon.shade !== undefined) L.push(`\t\tshade: ${q(icon.shade)},`);
		if (icon.hl !== undefined) L.push(`\t\thl: ${q(icon.hl)},`);
		if (icon.micro !== undefined) L.push(`\t\tmicro: ${q(icon.micro)},`);
		if (icon.microOnFill !== undefined) L.push(`\t\tmicroOnFill: ${q(icon.microOnFill)},`);
		if (icon.boil) L.push(`\t\tboil: [${q(icon.boil[0])}, ${q(icon.boil[1])}],`);
		if (icon.boilOnFill) L.push(`\t\tboilOnFill: [${q(icon.boilOnFill[0])}, ${q(icon.boilOnFill[1])}],`);
		L.push("\t},");
	}
	L.push(
		"};",
		"",
		"/** Every icon name, sorted. */",
		"export const ICON_NAMES = Object.keys(ICONS) as readonly IconName[];",
		"",
		"/** Product words that name an existing drawing (no duplicate paths). */",
		"export const ICON_ALIASES = {",
	);
	for (const a of Object.keys(aliases).sort()) L.push(`\t${q(a)}: ${q(aliases[a]!)},`);
	L.push(
		"} as const satisfies Readonly<Record<string, IconName>>;",
		"",
		"/** An alias name. */",
		"export type IconAlias = keyof typeof ICON_ALIASES;",
		"",
		"/** Narrow an arbitrary value to an icon name. */",
		"export function isIconName(value: unknown): value is IconName {",
		'\treturn typeof value === "string" && Object.prototype.hasOwnProperty.call(ICONS, value);',
		"}",
		"",
		"/** Resolve a name or alias to its icon name; null when unknown. */",
		"export function resolveIconName(value: string): IconName | null {",
		"\tif (isIconName(value)) return value;",
		"\treturn Object.prototype.hasOwnProperty.call(ICON_ALIASES, value) ? ICON_ALIASES[value as IconAlias] : null;",
		"}",
		"",
	);
	return L.join("\n");
}

/** components/icons/meta.ts — lightweight icon metadata for <Icon> (zero SVG path strings). */
export function emitMeta(icons: readonly CompiledIcon[], aliases: Readonly<Record<string, string>> = {}): string {
	const names = new Set(icons.map((i) => i.name));
	for (const [alias, target] of Object.entries(aliases)) {
		if (names.has(alias)) throw new Error(`alias "${alias}" collides with an icon of the same name`);
		if (!names.has(target)) throw new Error(`alias "${alias}" points at unknown icon "${target}"`);
	}
	const L: string[] = [
		"/**",
		` * ${HEADER("Lightweight cel icon metadata consumed by <Icon> (zero path strings; geometry lives in public/icons/sprite.svg).")}`,
		" */",
		"",
		'import type { IconTone } from "./tones.ts";',
		"",
		"export interface IconMeta {",
		"\treadonly grid: 24 | 48;",
		"\treadonly tone?: IconTone;",
		"\treadonly hasMicro?: true;",
		"\treadonly hasBoil?: true;",
		"\treadonly hasFill?: true;",
		"\treadonly hasHl?: true;",
		"}",
		"",
		"/** Every icon name (kebab-case, semantic — r9 §8.4). */",
		"export type IconName =",
	];
	icons.forEach((icon, i) => L.push(`\t| ${q(icon.name)}${i === icons.length - 1 ? ";" : ""}`));
	L.push("", "export const ICON_META: Readonly<Record<IconName, IconMeta>> = {");
	for (const icon of icons) {
		const fields: string[] = [`grid: ${icon.grid}`];
		if (icon.tone) fields.push(`tone: ${q(icon.tone)}`);
		if (icon.micro !== undefined) fields.push("hasMicro: true");
		if (icon.boil) fields.push("hasBoil: true");
		if (icon.fill !== undefined) fields.push("hasFill: true");
		if (icon.hl !== undefined) fields.push("hasHl: true");
		L.push(`\t${q(icon.name)}: { ${fields.join(", ")} },`);
	}
	L.push(
		"};",
		"",
		"/** Every icon name, sorted. */",
		"export const ICON_NAMES = Object.keys(ICON_META) as readonly IconName[];",
		"",
		"/** Product words that name an existing drawing (no duplicate paths). */",
		"export const ICON_ALIASES = {",
	);
	for (const a of Object.keys(aliases).sort()) L.push(`\t${q(a)}: ${q(aliases[a]!)},`);
	L.push(
		"} as const satisfies Readonly<Record<string, IconName>>;",
		"",
		"/** An alias name. */",
		"export type IconAlias = keyof typeof ICON_ALIASES;",
		"",
		"/** Narrow an arbitrary value to an icon name. */",
		"export function isIconName(value: unknown): value is IconName {",
		'\treturn typeof value === "string" && Object.prototype.hasOwnProperty.call(ICON_META, value);',
		"}",
		"",
		"/** Resolve a name or alias to its icon name; null when unknown. */",
		"export function resolveIconName(value: string): IconName | null {",
		"\tif (isIconName(value)) return value;",
		"\treturn Object.prototype.hasOwnProperty.call(ICON_ALIASES, value) ? ICON_ALIASES[value as IconAlias] : null;",
		"}",
		"",
	);
	return L.join("\n");
}

/** The `<path>` elements of one icon at full detail, painted via CSS vars. */
export function iconPaths(icon: CompiledIcon): string {
	const p = (d: string | undefined, layer: "fill" | "shade" | "onFill" | "ink" | "hl", cls: string = layer) =>
		d ? `<path class="icon-${cls}" d="${d}" style="fill:${layerPaint(layer, icon.tone)}"/>` : "";
	// On-fill ink goes UNDER the ground ink, so the outline stays clean where they meet.
	return [p(icon.fill, "fill"), p(icon.shade, "shade"), p(icon.inkOnFill, "onFill", "ink-on-fill"), p(icon.ink, "ink"), p(icon.hl, "hl")].join("");
}

/** The `<path>` elements of one icon at micro detail (≤16 px), painted via CSS vars. */
export function iconMicroPaths(icon: CompiledIcon): string {
	const p = (d: string | undefined, layer: "fill" | "shade" | "onFill" | "ink" | "hl", cls: string = layer) =>
		d ? `<path class="icon-${cls}" d="${d}" style="fill:${layerPaint(layer, icon.tone)}"/>` : "";
	return [p(icon.fill, "fill"), p(icon.shade, "shade"), p(icon.microOnFill, "onFill", "ink-on-fill"), p(icon.micro, "ink"), p(icon.hl, "hl")].join("");
}

/** The `<path>` and `.cel-boil` `<g>` elements of one live-boiling icon. */
export function iconBoilPaths(icon: CompiledIcon): string {
	const p = (d: string | undefined, layer: "fill" | "shade" | "onFill" | "ink" | "hl", cls: string = layer) =>
		d ? `<path class="icon-${cls}" d="${d}" style="fill:${layerPaint(layer, icon.tone)}"/>` : "";
	const onFillFrames = icon.boil && icon.inkOnFill
		? [icon.inkOnFill, icon.boilOnFill?.[0] || icon.inkOnFill, icon.boilOnFill?.[1] || icon.inkOnFill]
		: null;
	const inkFrames = icon.boil ? [icon.ink, icon.boil[0], icon.boil[1]] : null;
	const onFillBoil = onFillFrames
		? `<g class="cel-boil">${onFillFrames.map((d) => p(d, "onFill", "ink-on-fill")).join("")}</g>`
		: p(icon.inkOnFill, "onFill", "ink-on-fill");
	const inkBoil = inkFrames
		? `<g class="cel-boil">${inkFrames.map((d) => p(d, "ink")).join("")}</g>`
		: p(icon.ink, "ink");
	return [p(icon.fill, "fill"), p(icon.shade, "shade"), onFillBoil, inkBoil, p(icon.hl, "hl")].join("");
}

const SPRITE_BOIL_STYLE =
	"<defs><style>.cel-boil>*{opacity:0;animation:cel-boil var(--cel-boil-dur) step-end infinite}.cel-boil>:first-child{opacity:1}.cel-boil>:nth-child(2){animation-delay:calc(var(--cel-boil-dur)*-2/3)}.cel-boil>:nth-child(3){animation-delay:calc(var(--cel-boil-dur)*-1/3)}@keyframes cel-boil{0%{opacity:1}33.333%{opacity:0}100%{opacity:0}}@media(prefers-reduced-motion:reduce){.cel-boil>*{animation:none}}</style></defs>";

/** public/icons/sprite.svg — `<symbol id="name">`, plus `--micro` and `--boil` variants when present. */
export function emitSprite(icons: readonly CompiledIcon[]): string {
	const out: string[] = [];
	out.push('<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden">');
	out.push(`<!-- ${HEADER("Use: <svg viewBox=\"0 0 24 24\"><use href=\"/icons/sprite.svg#home\"/></svg>.")} -->`);
	out.push(SPRITE_BOIL_STYLE);
	for (const icon of icons) {
		const vb = `viewBox="0 0 ${icon.grid} ${icon.grid}"`;
		const title = `<title>${escapeXml(icon.label)}</title>`;
		out.push(`<symbol id="${icon.name}" ${vb}>${title}${iconPaths(icon)}</symbol>`);
		if (icon.micro !== undefined) {
			out.push(`<symbol id="${icon.name}--micro" ${vb}>${title}${iconMicroPaths(icon)}</symbol>`);
		}
		if (icon.boil) {
			out.push(`<symbol id="${icon.name}--boil" ${vb}>${title}${iconBoilPaths(icon)}</symbol>`);
		}
	}
	out.push("</svg>");
	out.push("");
	return out.join("\n");
}

function escapeXml(s: string): string {
	return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** A standalone SVG with literal colors (contact sheets, resvg previews —
 *  resvg does not resolve CSS custom properties). */
export function standaloneSvg(
	icon: CompiledIcon,
	colors: { ink: string; fill: string; shade: string; hl: string; onFill?: string; bg?: string },
	size: number,
	variant: "regular" | "micro" | "boil1" | "boil2" = "regular",
	tones = true,
): string {
	const [ink, onFill] = inkVariant(icon, variant);
	const g = icon.grid;
	const parts = [
		colors.bg ? `<rect width="${g}" height="${g}" fill="${colors.bg}"/>` : "",
		tones && icon.fill ? `<path d="${icon.fill}" fill="${colors.fill}"/>` : "",
		tones && icon.shade ? `<path d="${icon.shade}" fill="${colors.shade}"/>` : "",
		// Without the tone there is no color under it: on-fill ink is plain ink.
		onFill ? `<path d="${onFill}" fill="${tones ? (colors.onFill ?? colors.ink) : colors.ink}"/>` : "",
		ink ? `<path d="${ink}" fill="${colors.ink}"/>` : "",
		tones && icon.hl && size >= 20 ? `<path d="${icon.hl}" fill="${colors.hl}"/>` : "",
	];
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${g} ${g}" width="${size}" height="${size}">${parts.join("")}</svg>`;
}

/** The [ground ink, on-fill ink] pair of one ink variant (falls back to the
 *  regular ink when the icon has no such variant). */
export function inkVariant(icon: CompiledIcon, variant: "regular" | "micro" | "boil1" | "boil2"): [string, string | undefined] {
	if (variant === "micro" && icon.micro !== undefined) return [icon.micro, icon.microOnFill];
	if ((variant === "boil1" || variant === "boil2") && icon.boil) {
		const i = variant === "boil1" ? 0 : 1;
		return [icon.boil[i], icon.boilOnFill?.[i] || undefined];
	}
	return [icon.ink, icon.inkOnFill];
}
